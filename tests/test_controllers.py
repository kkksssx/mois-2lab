import json
import os
import sys
import tempfile
import time
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.constants import *  # noqa
from app.controllers import (КонтроллерМероприятий, КонтроллерПользователей,
                             КонтроллерСессии, КонтроллерХранения)
from app.errors import ОшибкаПлатформы
from app.model import Репозиторий, Пользователь


class БазовыйТест(unittest.TestCase):
    def setUp(self):
        self.папка = tempfile.TemporaryDirectory()
        self.репо = Репозиторий(os.path.join(self.папка.name, "s.pkl"))
        self.хран = КонтроллерХранения(self.репо)
        self.сесс = КонтроллерСессии(self.репо, self.хран)
        self.мер = КонтроллерМероприятий(self.репо, self.сесс)
        self.пол = КонтроллерПользователей(self.репо)
        self.орг = self._завести("Препод", "t@x.ru", "Организатор")
        self.студ = self._завести("Студент", "s@x.ru")
        self.студ2 = self._завести("Студент2", "s2@x.ru")

    def tearDown(self):
        self.папка.cleanup()

    def _завести(self, имя, email, роль=None):
        self.пол.регистрация(json.dumps({"имя": имя, "email": email, "пароль": "secret1"}))
        ид = json.loads(self.пол.аутентификация(email, "secret1"))["идПользователя"]
        if роль:
            self.пол.управлениеПравами(ид, роль)
        return ид

    def _создать(self, зал=True, запись=True):
        м = self.мер.создатьМероприятие(json.dumps({
            "идОрганизатора": self.орг, "тема": "Вебинар", "датаВремя": int(time.time()),
            "типДоступа": "По ссылке", "запись": запись, "залОжидания": зал}))
        return м.идМероприятия


class ТестПользователей(БазовыйТест):
    def test_вход(self):
        self.assertEqual(json.loads(self.пол.аутентификация("T@x.ru", "secret1"))["роль"], "Организатор")
        self.assertEqual(self.пол.аутентификация("t@x.ru", "bad"), "")
        self.assertTrue(self.пол.аутентификация("Студент", "secret1"))  # вход по имени

    def test_валидация(self):
        for плохие in ({"имя": "", "email": "a@b.ru", "пароль": "123456"},
                       {"имя": "A", "email": "bad", "пароль": "123456"},
                       {"имя": "A", "email": "a@b.ru", "пароль": "123"}):
            with self.assertRaises(ОшибкаПлатформы):
                self.пол.регистрация(json.dumps(плохие))
        with self.assertRaises(ОшибкаПлатформы):   # дубль email
            self.пол.регистрация(json.dumps({"имя": "A", "email": "s@x.ru", "пароль": "123456"}))

    def test_пароль_не_хранится_открыто(self):
        self.assertNotIn("secret1", self.репо.пользователи[self.студ]._пароль)

    def test_абстрактный_пользователь(self):
        with self.assertRaises(TypeError):
            Пользователь("1", "a", "a@a", "p", "Участник")


class ТестСценария(БазовыйТест):
    def test_полный_сценарий_вебинара(self):
        ид = self._создать()
        # участник не может подключиться, пока организатор не открыл
        with self.assertRaises(ОшибкаПлатформы):
            self.сесс.подключитьУчастника(ид, self.студ)
        self.мер.открытьКонференцию(ид, self.орг)
        self.assertEqual(self.мер.получитьСтатус(ид), СТАТУС_ИДЁТ)
        орг = self.сесс.подключитьУчастника(ид, self.орг)
        self.assertEqual(орг.статусПодключения, УЧ_ПОДКЛЮЧЁН)
        # студент попадает в зал ожидания
        с = self.сесс.подключитьУчастника(ид, self.студ)
        self.assertEqual(с.статусПодключения, УЧ_ОЖИДАНИЕ)
        with self.assertRaises(ОшибкаПлатформы):   # из зала писать нельзя
            self.сесс.отправитьСообщение(ид, self.студ, "привет")
        # допускает только организатор
        with self.assertRaises(ОшибкаПлатформы):
            self.сесс.допуститьУчастника(с.идЗаписи, self.студ2)
        self.сесс.допуститьУчастника(с.идЗаписи, self.орг)
        self.сесс.отправитьСообщение(ид, self.студ, "Здравствуйте")
        # микрофон: сам себе включить нельзя, организатор может
        with self.assertRaises(ОшибкаПлатформы):
            self.сесс.управлятьМикрофоном(с.идЗаписи, True, self.студ)
        self.сесс.управлятьМикрофоном(с.идЗаписи, True, self.орг)
        self.сесс.управлятьМикрофоном(с.идЗаписи, False, self.студ)
        # чужим микрофоном студент управлять не может
        с2 = self.сесс.подключитьУчастника(ид, self.студ2)
        self.сесс.допуститьУчастника(с2.идЗаписи, self.орг)
        self.сесс.управлятьМикрофоном(с2.идЗаписи, True, self.орг)
        with self.assertRaises(ОшибкаПлатформы):
            self.сесс.управлятьМикрофоном(с2.идЗаписи, False, self.студ)
        self.сесс.управлятьДемонстрацией(ид, True, self.орг)
        with self.assertRaises(ОшибкаПлатформы):
            self.сесс.управлятьДемонстрацией(ид, True, self.студ)
        # студент не может завершить чужую встречу
        with self.assertRaises(ОшибкаПлатформы):
            self.мер.завершитьВстречу(ид, self.студ)
        self.сесс.отключитьУчастника(с2.идЗаписи)
        self.мер.завершитьВстречу(ид, self.орг)
        self.assertEqual(self.мер.получитьСтатус(ид), СТАТУС_ЗАВЕРШЕНО)
        ст = self.хран.получитьСтатистику(ид)
        self.assertEqual(ст.количествоУчастников, 2)
        self.assertEqual(ст.активностьВЧате, 1)
        self.assertEqual(self.хран.получитьПосещаемость(ид), 100)
        запись = self.хран.получитьЗапись(ид)
        self.assertIsNotNone(запись)
        self.assertTrue(os.path.exists(запись._ссылкаНаФайл))

    def test_без_зала_ожидания_и_без_записи(self):
        ид = self._создать(зал=False, запись=False)
        self.мер.открытьКонференцию(ид, self.орг)
        self.assertEqual(self.сесс.подключитьУчастника(ид, self.студ).статусПодключения, УЧ_ПОДКЛЮЧЁН)
        self.мер.завершитьВстречу(ид, self.орг)
        self.assertIsNone(self.хран.получитьЗапись(ид))

    def test_создавать_может_только_организатор(self):
        with self.assertRaises(ОшибкаПлатформы):
            self.мер.создатьМероприятие(json.dumps(
                {"идОрганизатора": self.студ, "тема": "x", "датаВремя": 1}))
        with self.assertRaises(ОшибкаПлатформы):
            self.мер.создатьМероприятие(json.dumps(
                {"идОрганизатора": self.орг, "тема": " ", "датаВремя": 1}))

    def test_ссылка_и_приглашение(self):
        ид = self._создать()
        self.assertTrue(self.мер.получитьСсылкуДоступа(ид).startswith("https://"))

    def test_сохранение_между_запусками(self):
        ид = self._создать()
        репо2 = Репозиторий(self.репо._путь)
        self.assertIn(ид, репо2.мероприятия)
        # ссылка организатор -> мероприятие должна остаться тем же объектом
        орг = репо2.пользователи[self.орг]
        self.assertIs(орг.мероприятия[0], репо2.мероприятия[ид])

    def test_синхронизация_двух_процессов(self):
        репо2 = Репозиторий(self.репо._путь)
        мер2 = КонтроллерМероприятий(репо2, КонтроллерСессии(репо2, КонтроллерХранения(репо2)))
        ид = self._создать()
        time.sleep(0.05)
        self.assertEqual(мер2.получитьСтатус(ид), СТАТУС_СОЗДАНО)  # второй процесс увидел


if __name__ == "__main__":
    unittest.main()
