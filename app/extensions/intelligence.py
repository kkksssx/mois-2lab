"""Направление 2. Интеллектуализация (розовые классы на диаграмме)."""
from __future__ import annotations

from typing import List

from ..model import ЗаписьВстречи
from ..views.interfaces import IПредставление

_НЕ_РЕАЛИЗОВАНО = "Направление развития: в базовой версии не реализовано"


class Перевод:
    def __init__(self, идПеревода: str, целевойЯзык: str, текстПеревода: str) -> None:
        self.идПеревода = идПеревода
        self.целевойЯзык = целевойЯзык
        self.текстПеревода = текстПеревода


class Конспект:
    def __init__(self, идКонспекта: str, краткоеСодержание: str, ключевыеТезисы: str,
                 датаСоздания: int) -> None:
        self.идКонспекта = идКонспекта
        self.краткоеСодержание = краткоеСодержание
        self.ключевыеТезисы = ключевыеТезисы
        self.датаСоздания = датаСоздания


class Транскрипция:
    def __init__(self, идТранскрипции: str, текст: str, язык: str, времяСоздания: int,
                 запись: ЗаписьВстречи) -> None:
        self.идТранскрипции = идТранскрипции
        self.текст = текст
        self.язык = язык
        self.времяСоздания = времяСоздания
        # Связь «ЗаписьВстречи 1 — имеет — 0..1 Транскрипция». Чтобы не менять старый
        # класс ЗаписьВстречи, ссылка хранится в новом классе (в обратную сторону).
        self.запись = запись
        self.конспект: Конспект = None          # «порождает», 0..1
        self.переводы: List[Перевод] = []       # «переводится», 0..*


class СервисРаспознаванияРечи:
    def преобразоватьВТекст(self, аудио: str) -> str:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)

    def определитьЯзык(self, текст: str) -> str:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)

    def _очиститьШумы(self, аудио: str) -> str:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)


class СервисСуммаризации:
    def выделитьТезисы(self, текст: str) -> List[str]:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)

    def сократитьТекст(self, текст: str) -> str:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)


class СервисПеревода:
    def перевести(self, текст: str, язык: str) -> str:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)


class КонтроллерИнтеллектуальныхФункций:
    def __init__(self, распознавание: СервисРаспознаванияРечи,
                 суммаризация: СервисСуммаризации, перевод: СервисПеревода) -> None:
        self._распознавание = распознавание
        self._суммаризация = суммаризация
        self._перевод = перевод

    def распознатьРечь(self, аудио: str) -> Транскрипция:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)

    def создатьКонспект(self, транскрипция: Транскрипция) -> Конспект:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)

    def перевестиВРеальномВремени(self, текст: str, язык: str) -> Перевод:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)

    def получитьТранскрипцию(self, ид: str) -> Транскрипция:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)


class IПредставлениеИнтеллектуальныхФункций(IПредставление):  # <<interface>>
    def отобразитьТранскрипцию(self, транскрипция: Транскрипция) -> None:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)

    def показатьКонспект(self, конспект: Конспект) -> None:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)

    def отобразитьПеревод(self, перевод: Перевод) -> None:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)

    def настроитьЯзыкПеревода(self, язык: str) -> None:
        raise NotImplementedError(_НЕ_РЕАЛИЗОВАНО)
