"""КонтроллерМероприятий: создание, открытие и завершение мероприятий."""
from __future__ import annotations

import json
import uuid
from typing import List

from ..constants import (ПРИГЛАШЕНИЕ_ОТПРАВЛЕНО, СТАТУС_ЗАВЕРШЕНО, СТАТУС_ИДЁТ,
                         СТАТУС_СОЗДАНО)
from ..errors import ОшибкаПлатформы
from ..model import Мероприятие, Организатор, Приглашение, Репозиторий
from .session_controller import КонтроллерСессии


class КонтроллерМероприятий:
    def __init__(self, репозиторий: Репозиторий, контроллерСессии: КонтроллерСессии) -> None:
        self._репо = репозиторий
        # по sequence-диаграмме контроллер мероприятий вызывает контроллер сессии
        self._сессии = контроллерСессии

    # ---------- методы из диаграммы ----------
    def создатьМероприятие(self, данные: str) -> Мероприятие:
        """данные — JSON: идОрганизатора, тема, датаВремя, типДоступа, запись, залОжидания."""
        self._репо.синхронизировать()
        try:
            поля = json.loads(данные)
        except (ValueError, TypeError):
            raise ОшибкаПлатформы("Данные мероприятия переданы в неверном формате")
        # проверка прав на «сервере»: создавать может только Организатор
        организатор = self._репо.пользователи.get(поля.get("идОрганизатора", ""))
        if not isinstance(организатор, Организатор):
            raise ОшибкаПлатформы("Создавать мероприятия может только пользователь с ролью «Организатор»")
        тема = str(поля.get("тема", "")).strip()
        if not тема:
            raise ОшибкаПлатформы("Введите тему мероприятия")

        мероприятие = Мероприятие(uuid.uuid4().hex[:8], тема, int(поля["датаВремя"]),
                                  поля.get("типДоступа", "По ссылке"),
                                  bool(поля.get("запись", True)),
                                  bool(поля.get("залОжидания", True)))
        # композиция: приглашение с ссылкой создаётся вместе с мероприятием
        ссылка = "https://conference.local/join/" + uuid.uuid4().hex[:10]
        мероприятие.приглашения.append(
            Приглашение(uuid.uuid4().hex[:8], ПРИГЛАШЕНИЕ_ОТПРАВЛЕНО, ссылка))
        организатор.мероприятия.append(мероприятие)
        self._репо.мероприятия[мероприятие.идМероприятия] = мероприятие
        self._репо.сохранить()
        return мероприятие

    def открытьКонференцию(self, ид: str, идПользователя: str = "") -> None:
        """[отклонение Д6] добавлен идПользователя для проверки прав организатора."""
        self._репо.синхронизировать()
        мероприятие = self._репо.найтиМероприятие(ид)
        self._проверитьОрганизатора(ид, идПользователя)
        if мероприятие._статус == СТАТУС_ЗАВЕРШЕНО:
            raise ОшибкаПлатформы("Мероприятие уже завершено")
        if мероприятие._статус == СТАТУС_ИДЁТ:
            return
        мероприятие._статус = СТАТУС_ИДЁТ     # в sequence: статус = LIVE
        self._репо.сохранить()
        self._сессии.запуститьСессию(ид)      # в sequence: создатьСессию(eventId)

    def завершитьВстречу(self, ид: str, идПользователя: str = "") -> None:
        self._репо.синхронизировать()
        мероприятие = self._репо.найтиМероприятие(ид)
        self._проверитьОрганизатора(ид, идПользователя)
        if мероприятие._статус != СТАТУС_ИДЁТ:
            raise ОшибкаПлатформы("Встреча не идёт, завершать нечего")
        мероприятие._статус = СТАТУС_ЗАВЕРШЕНО  # в sequence: статус = FINISHED
        self._репо.сохранить()
        self._сессии.завершитьСессию(ид)        # там же сохраняется запись

    # ---------- дополнительные методы [отклонение] ----------
    # Нужны интерфейсу: в диаграмме нет способа получить список мероприятий,
    # статус (он приватный) и ссылку (она тоже приватная).

    def получитьМероприятия(self, идПользователя: str) -> List[Мероприятие]:
        """Все мероприятия по возрастанию даты.
        В модели нет связи Пользователь—Мероприятие для участников, поэтому каждый
        пользователь видит все мероприятия (подробнее в отчёте)."""
        self._репо.синхронизировать()
        return sorted(self._репо.мероприятия.values(), key=lambda м: м.датаВремя)

    def получитьМероприятие(self, ид: str) -> Мероприятие:
        self._репо.синхронизировать()
        return self._репо.найтиМероприятие(ид)

    def получитьСтатус(self, ид: str) -> str:
        self._репо.синхронизировать()
        return self._репо.найтиМероприятие(ид)._статус

    def получитьСсылкуДоступа(self, ид: str) -> str:
        self._репо.синхронизировать()
        приглашения = self._репо.найтиМероприятие(ид).приглашения
        return приглашения[0]._ссылкаДоступа if приглашения else ""

    def являетсяОрганизатором(self, ид: str, идПользователя: str) -> bool:
        self._репо.синхронизировать()
        return self._репо.этоОрганизатор(ид, идПользователя)

    def _проверитьОрганизатора(self, ид: str, идПользователя: str) -> None:
        if идПользователя and not self._репо.этоОрганизатор(ид, идПользователя):
            raise ОшибкаПлатформы("Управлять мероприятием может только его организатор")
