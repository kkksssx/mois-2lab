"""КонтроллерСессии: онлайн-комната, участники, микрофон, чат."""
from __future__ import annotations

import os
import time
import uuid
from typing import List

from ..constants import (СТАТУС_ИДЁТ, УЧ_НЕ_ДОПУЩЕН, УЧ_ОЖИДАНИЕ, УЧ_ОТКЛЮЧЁН,
                         УЧ_ПОДКЛЮЧЁН)
from ..errors import ОшибкаПлатформы
from ..model import (Репозиторий, СессияСвязи, СообщениеЧата, Участник,
                     УчастникСессии)
from .storage_controller import КонтроллерХранения


class КонтроллерСессии:
    def __init__(self, репозиторий: Репозиторий, контроллерХранения: КонтроллерХранения) -> None:
        self._репо = репозиторий
        self._хранение = контроллерХранения

    # ---------- методы из диаграммы ----------
    def запуститьСессию(self, ид: str) -> СессияСвязи:
        """ид — идентификатор мероприятия (так в sequence-диаграмме: создатьСессию(eventId))."""
        self._репо.синхронизировать()
        мероприятие = self._репо.найтиМероприятие(ид)
        if мероприятие.сессия is None:
            мероприятие.сессия = СессияСвязи(uuid.uuid4().hex[:8])
            self._репо.сохранить()
        return мероприятие.сессия

    def подключитьУчастника(self, ид: str, идПользователя: str = "") -> УчастникСессии:
        """[отклонение Д6] В диаграмме один параметр ид, но чтобы подключить человека,
        нужно знать и мероприятие, и пользователя (в sequence: запросНаПодключение(userId,
        eventId)). Поэтому ид — мероприятие, а пользователь — второй параметр."""
        self._репо.синхронизировать()
        мероприятие = self._репо.найтиМероприятие(ид)
        # ветка alt из sequence-диаграммы: организатор ещё не открыл встречу
        if мероприятие.сессия is None or мероприятие._статус != СТАТУС_ИДЁТ:
            raise ОшибкаПлатформы("Организатор ещё не открыл конференцию. Попробуйте позже.")
        пользователь = self._репо.найтиПользователя(идПользователя)
        сессия = мероприятие.сессия
        этоОрг = self._репо.этоОрганизатор(ид, идПользователя)

        запись = next((у for у in сессия.участники if у.идПользователя == идПользователя), None)
        if запись is None:
            # организатора пускаем сразу, остальных — в зал ожидания, если он включён
            if этоОрг or not мероприятие.залОжидания:
                статус = УЧ_ПОДКЛЮЧЁН
            else:
                статус = УЧ_ОЖИДАНИЕ
            запись = УчастникСессии(uuid.uuid4().hex[:8], этоОрг, статус,
                                    идПользователя, пользователь.имя)
            сессия.участники.append(запись)
        elif запись.статусПодключения == УЧ_ОТКЛЮЧЁН:
            запись.статусПодключения = УЧ_ПОДКЛЮЧЁН          # вернулся — повторно не ждёт
        elif запись.статусПодключения == УЧ_НЕ_ДОПУЩЕН:
            запись.статусПодключения = УЧ_ПОДКЛЮЧЁН if (этоОрг or not мероприятие.залОжидания) else УЧ_ОЖИДАНИЕ

        if isinstance(пользователь, Участник):
            пользователь.статусПодключения = запись.статусПодключения
        self._хранение.обновитьСтатистику(ид)
        self._репо.сохранить()
        return запись

    def управлятьМикрофоном(self, ид: str, вкл: bool, идИнициатора: str = "") -> None:
        """ид — идентификатор УчастникаСессии (его идЗаписи).
        [отклонение Д6] добавлен идИнициатора, чтобы проверять права на сервере:
        чужим микрофоном может управлять только организатор мероприятия."""
        self._репо.синхронизировать()
        мероприятие, участник = self._репо.найтиУчастника(ид)
        if участник.статусПодключения != УЧ_ПОДКЛЮЧЁН:
            raise ОшибкаПлатформы("Участник не подключён к конференции")
        if идИнициатора:
            организатор = self._репо.этоОрганизатор(мероприятие.идМероприятия, идИнициатора)
            сам_себя = идИнициатора == участник.идПользователя
            if not организатор and not (сам_себя and not вкл):
                raise ОшибкаПлатформы("Включить микрофон участнику может только организатор")
        участник.праваМикрофона = вкл
        self._репо.сохранить()

    # ---------- дополнительные методы [отклонение Д7] ----------
    # Их нет в диаграмме классов, но они нужны по sequence-диаграмме, макету экрана
    # конференции и тексту описания (чат, демонстрация экрана, зал ожидания).

    def допуститьУчастника(self, ид: str, идИнициатора: str) -> None:
        """«пустить» из sequence-диаграммы: организатор выпускает из зала ожидания."""
        self._репо.синхронизировать()
        мероприятие, участник = self._репо.найтиУчастника(ид)
        if not self._репо.этоОрганизатор(мероприятие.идМероприятия, идИнициатора):
            raise ОшибкаПлатформы("Допускать участников может только организатор")
        if участник.статусПодключения == УЧ_ОЖИДАНИЕ:
            участник.статусПодключения = УЧ_ПОДКЛЮЧЁН
            пользователь = self._репо.пользователи.get(участник.идПользователя)
            if isinstance(пользователь, Участник):
                пользователь.статусПодключения = УЧ_ПОДКЛЮЧЁН
        self._хранение.обновитьСтатистику(мероприятие.идМероприятия)
        self._репо.сохранить()

    def управлятьДемонстрацией(self, ид: str, вкл: bool, идИнициатора: str) -> None:
        """Включает/выключает демонстрацию экрана. ид — идентификатор мероприятия."""
        self._репо.синхронизировать()
        мероприятие = self._репо.найтиМероприятие(ид)
        if мероприятие.сессия is None:
            raise ОшибкаПлатформы("Сессия не запущена")
        # в модели у УчастникаСессии нет права на демонстрацию, поэтому только организатор
        if not self._репо.этоОрганизатор(ид, идИнициатора):
            raise ОшибкаПлатформы("Демонстрацию экрана включает только организатор")
        мероприятие.сессия.демонстрацияЭкрана = вкл
        self._репо.сохранить()

    def отправитьСообщение(self, ид: str, идАвтора: str, текст: str) -> СообщениеЧата:
        """Сообщение в чат. ид — идентификатор мероприятия."""
        self._репо.синхронизировать()
        мероприятие = self._репо.найтиМероприятие(ид)
        сессия = мероприятие.сессия
        if сессия is None:
            raise ОшибкаПлатформы("Сессия не запущена")
        запись = next((у for у in сессия.участники if у.идПользователя == идАвтора), None)
        if запись is None or запись.статусПодключения != УЧ_ПОДКЛЮЧЁН:
            raise ОшибкаПлатформы("Писать в чат можно только после допуска в конференцию")
        текст = текст.strip()
        if not текст:
            raise ОшибкаПлатформы("Пустое сообщение")
        сообщение = СообщениеЧата(uuid.uuid4().hex[:8], текст, int(time.time()), запись.имя)
        сессия.сообщения.append(сообщение)
        self._хранение.обновитьСтатистику(ид)
        self._репо.сохранить()
        return сообщение

    def получитьУчастников(self, ид: str) -> List[УчастникСессии]:
        self._репо.синхронизировать()
        сессия = self._репо.найтиМероприятие(ид).сессия
        return list(сессия.участники) if сессия else []

    def получитьСообщения(self, ид: str) -> List[СообщениеЧата]:
        self._репо.синхронизировать()
        сессия = self._репо.найтиМероприятие(ид).сессия
        return list(сессия.сообщения) if сессия else []

    def отключитьУчастника(self, ид: str) -> None:
        """Участник вышел из комнаты. ид — идЗаписи участника сессии."""
        self._репо.синхронизировать()
        try:
            _, участник = self._репо.найтиУчастника(ид)
        except ОшибкаПлатформы:
            return
        if участник.статусПодключения == УЧ_ОЖИДАНИЕ:
            участник.статусПодключения = УЧ_НЕ_ДОПУЩЕН
        elif участник.статусПодключения == УЧ_ПОДКЛЮЧЁН:
            участник.статусПодключения = УЧ_ОТКЛЮЧЁН
        пользователь = self._репо.пользователи.get(участник.идПользователя)
        if isinstance(пользователь, Участник):
            пользователь.статусПодключения = "Не подключён"
        self._репо.сохранить()

    def завершитьСессию(self, ид: str) -> None:
        """закрытьСессию(eventId) из sequence-диаграммы. ид — идентификатор мероприятия."""
        self._репо.синхронизировать()
        мероприятие = self._репо.найтиМероприятие(ид)
        сессия = мероприятие.сессия
        if сессия is None:
            return
        сессия.видеопоток = сессия.аудиопоток = сессия.демонстрацияЭкрана = False
        for участник in сессия.участники:
            if участник.статусПодключения == УЧ_ОЖИДАНИЕ:
                участник.статусПодключения = УЧ_НЕ_ДОПУЩЕН
            elif участник.статусПодключения == УЧ_ПОДКЛЮЧЁН:
                участник.статусПодключения = УЧ_ОТКЛЮЧЁН
        self._хранение.обновитьСтатистику(ид)
        self._репо.сохранить()
        if мероприятие.запись:
            # настоящей записи видео у нас нет, поэтому создаём файл-заглушку
            папка = os.path.join(self._репо.папкаДанных, "recordings")
            os.makedirs(папка, exist_ok=True)
            путь = os.path.join(папка, мероприятие.идМероприятия + ".webm")
            with open(путь, "w", encoding="utf-8") as f:
                f.write("Имитация записи мероприятия: " + мероприятие.тема)
            self._хранение.сохранитьЗапись(ид, путь)
