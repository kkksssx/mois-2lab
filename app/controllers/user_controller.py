"""КонтроллерПользователей: регистрация, вход, права."""
from __future__ import annotations

import hashlib
import hmac
import json
import os
import re
import uuid

from ..constants import РОЛЬ_ОРГАНИЗАТОР, РОЛЬ_УЧАСТНИК
from ..errors import ОшибкаПлатформы
from ..model import Организатор, Репозиторий, Участник


class КонтроллерПользователей:
    def __init__(self, репозиторий: Репозиторий) -> None:
        self._репо = репозиторий
        self.причинаОшибки: str = ""  # почему _проверитьДанные вернул False

    # ---------- методы из диаграммы ----------
    def регистрация(self, данные: str) -> None:
        """данные — JSON-строка {"имя", "email", "пароль"} (в диаграмме тип String)."""
        self._репо.синхронизировать()
        if not self._проверитьДанные(данные):
            raise ОшибкаПлатформы(self.причинаОшибки)
        поля = json.loads(данные)
        email = поля["email"].strip().lower()
        for пользователь in self._репо.пользователи.values():
            if пользователь.email.lower() == email:
                raise ОшибкаПлатформы("Пользователь с таким email уже зарегистрирован")
        # все новые пользователи — обычные участники, роль меняется через управлениеПравами
        новый = Участник(uuid.uuid4().hex[:8], поля["имя"].strip(), email,
                         self._хэшПароля(поля["пароль"]))
        self._репо.пользователи[новый.идПользователя] = новый
        self._репо.сохранить()

    def аутентификация(self, login: str, pass_: str) -> str:
        """Возвращает JSON-строку с идПользователя, именем и ролью. Пустая строка —
        логин или пароль неверные. (В диаграмме возвращается String.)"""
        self._репо.синхронизировать()
        логин = login.strip().lower()
        for пользователь in self._репо.пользователи.values():
            подходит = логин in (пользователь.email.lower(), пользователь.имя.lower())
            if подходит and self._проверитьХэш(pass_, пользователь._пароль):
                return json.dumps({"идПользователя": пользователь.идПользователя,
                                   "имя": пользователь.имя, "роль": пользователь.роль},
                                  ensure_ascii=False)
        return ""

    def управлениеПравами(self, ид: str, роль: str) -> None:
        """Меняет роль пользователя: пересоздаём объект нужного класса."""
        self._репо.синхронизировать()
        if роль not in (РОЛЬ_ОРГАНИЗАТОР, РОЛЬ_УЧАСТНИК):
            raise ОшибкаПлатформы("Неизвестная роль: " + роль)
        старый = self._репо.найтиПользователя(ид)
        if старый.роль == роль:
            return
        класс = Организатор if роль == РОЛЬ_ОРГАНИЗАТОР else Участник
        новый = класс(старый.идПользователя, старый.имя, старый.email, старый._пароль)
        if isinstance(старый, Организатор) and isinstance(новый, Организатор):
            новый.мероприятия = старый.мероприятия
        self._репо.пользователи[ид] = новый
        self._репо.сохранить()

    def _проверитьДанные(self, данные: str) -> bool:
        """Проверка данных регистрации. Причина отказа кладётся в self.причинаОшибки."""
        try:
            поля = json.loads(данные)
        except (ValueError, TypeError):
            self.причинаОшибки = "Данные регистрации переданы в неверном формате"
            return False
        if not str(поля.get("имя", "")).strip():
            self.причинаОшибки = "Введите имя"
            return False
        if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", str(поля.get("email", "")).strip()):
            self.причинаОшибки = "Введите корректный email"
            return False
        if len(str(поля.get("пароль", ""))) < 6:
            self.причинаОшибки = "Пароль должен быть не короче 6 символов"
            return False
        self.причинаОшибки = ""
        return True

    # ---------- вспомогательное (не из диаграммы) ----------
    @staticmethod
    def _хэшПароля(пароль: str) -> str:
        # bcrypt/argon2 из рекомендаций не стал ставить (нужны сторонние пакеты),
        # взял PBKDF2 из стандартной библиотеки — идея та же: соль + медленный хэш
        соль = os.urandom(16)
        хэш = hashlib.pbkdf2_hmac("sha256", пароль.encode("utf-8"), соль, 100_000)
        return соль.hex() + "$" + хэш.hex()

    @staticmethod
    def _проверитьХэш(пароль: str, сохранённый: str) -> bool:
        try:
            соль_hex, хэш_hex = сохранённый.split("$")
        except ValueError:
            return False
        хэш = hashlib.pbkdf2_hmac("sha256", пароль.encode("utf-8"),
                                  bytes.fromhex(соль_hex), 100_000)
        return hmac.compare_digest(хэш.hex(), хэш_hex)
