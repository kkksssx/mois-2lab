"""КонтроллерХранения: записи встреч, файлы, статистика."""
from __future__ import annotations

import os
import time
import uuid
from typing import Optional

from ..constants import УЧ_ОТКЛЮЧЁН, УЧ_ПОДКЛЮЧЁН
from ..model import Репозиторий, Статистика, ЗаписьВстречи, Файл


class КонтроллерХранения:
    def __init__(self, репозиторий: Репозиторий) -> None:
        self._репо = репозиторий

    # ---------- методы из диаграммы ----------
    def сохранитьЗапись(self, ид: str, файл: str) -> None:
        """ид — идентификатор мероприятия, файл — путь к файлу записи."""
        self._репо.синхронизировать()
        мероприятие = self._репо.найтиМероприятие(ид)
        сессия = мероприятие.сессия
        длительность = int(time.time()) - сессия._началоСессии if сессия else 0
        запись = ЗаписьВстречи(uuid.uuid4().hex[:8], файл, длительность, int(time.time()))
        мероприятие.записи.append(запись)
        # сам файл записи тоже кладём в «файлы мероприятия»
        размер = os.path.getsize(файл) if os.path.exists(файл) else 0
        расширение = os.path.splitext(файл)[1].lstrip(".") or "bin"
        мероприятие.файлы.append(Файл(uuid.uuid4().hex[:8], os.path.basename(файл),
                                      размер, расширение))
        self._репо.сохранить()

    def получитьСтатистику(self, ид: str) -> Статистика:
        self._репо.синхронизировать()
        мероприятие = self._репо.найтиМероприятие(ид)
        self._пересчитать(ид)
        return мероприятие.статистика

    def получитьЗапись(self, ид: str) -> Optional[ЗаписьВстречи]:
        """Последняя запись мероприятия или None, если записи нет."""
        self._репо.синхронизировать()
        записи = self._репо.найтиМероприятие(ид).записи
        return записи[-1] if записи else None

    # ---------- дополнительные методы [отклонение Д7] ----------
    def обновитьСтатистику(self, ид: str) -> None:
        """Вызывается контроллером сессии после подключения/сообщений."""
        self._пересчитать(ид)

    def получитьСсылкуНаЗапись(self, ид: str) -> str:
        """Путь к файлу последней записи (поле ссылкаНаФайл приватное, поэтому через метод)."""
        запись = self.получитьЗапись(ид)
        return запись._ссылкаНаФайл if запись else ""

    def получитьПосещаемость(self, ид: str) -> int:
        """Процент допущенных от всех, кто пытался подключиться.
        На макете есть «Посещаемость: 85%», а в классе Статистика такого поля нет."""
        self._репо.синхронизировать()
        сессия = self._репо.найтиМероприятие(ид).сессия
        if сессия is None:
            return 0
        обычные = [у for у in сессия.участники
                   if not self._репо.этоОрганизатор(ид, у.идПользователя)]
        if not обычные:
            return 0
        допущено = [у for у in обычные if у.статусПодключения in (УЧ_ПОДКЛЮЧЁН, УЧ_ОТКЛЮЧЁН)]
        return round(len(допущено) * 100 / len(обычные))

    def _пересчитать(self, ид: str) -> None:
        мероприятие = self._репо.найтиМероприятие(ид)
        if мероприятие.сессия is None:
            return
        сессия = мероприятие.сессия
        # считаем только тех, кого реально пустили в конференцию (организатор не в счёт)
        мероприятие.статистика.количествоУчастников = len(
            [у for у in сессия.участники
             if у.статусПодключения in (УЧ_ПОДКЛЮЧЁН, УЧ_ОТКЛЮЧЁН)
             and not self._репо.этоОрганизатор(ид, у.идПользователя)])
        мероприятие.статистика.активностьВЧате = len(сессия.сообщения)
