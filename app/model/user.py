"""Пользователи: абстрактный Пользователь и его наследники Организатор и Участник."""
from __future__ import annotations

from abc import ABC
from typing import List

from ..constants import РОЛЬ_ОРГАНИЗАТОР, РОЛЬ_УЧАСТНИК


class Пользователь(ABC):
    """Абстрактный пользователь платформы (на диаграмме класс с буквой A)."""

    def __init__(self, идПользователя: str, имя: str, email: str,
                 пароль: str, роль: str) -> None:
        # на диаграмме класс абстрактный, значит напрямую создавать его нельзя
        if type(self) is Пользователь:
            raise TypeError("Пользователь — абстрактный класс, создайте Организатора или Участника")
        self.идПользователя: str = идПользователя
        self.имя: str = имя
        self.email: str = email
        # на диаграмме -пароль (приватный). Здесь лежит не сам пароль, а его хэш.
        # Одно подчёркивание — договорённость, что трогать может только контроллер.
        self._пароль: str = пароль
        self.роль: str = роль


class Организатор(Пользователь):
    """Создатель мероприятий, имеет расширенные права."""

    def __init__(self, идПользователя: str, имя: str, email: str, пароль: str) -> None:
        super().__init__(идПользователя, имя, email, пароль, РОЛЬ_ОРГАНИЗАТОР)
        self.праваМодерации: bool = True
        # ассоциация «создаёт»: Организатор 1 -> 0..* Мероприятие (стрелка к Мероприятию)
        self.мероприятия: List["Мероприятие"] = []  # noqa: F821


class Участник(Пользователь):
    """Приглашённый пользователь, подключается к чужим мероприятиям."""

    def __init__(self, идПользователя: str, имя: str, email: str, пароль: str) -> None:
        super().__init__(идПользователя, имя, email, пароль, РОЛЬ_УЧАСТНИК)
        self.статусПодключения: str = "Не подключён"
