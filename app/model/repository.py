"""Репозиторий — хранилище объектов модели.

[отклонение Д1] В базовой диаграмме классов репозитория нет, хотя на обеих
sequence-диаграммах есть объект «Репозиторий». Без него контроллерам негде хранить
объекты, поэтому добавил простой класс: словари в памяти + сохранение в файл (pickle).

Файл перечитывается, если его изменил другой процесс. Благодаря этому можно запустить
два окна приложения (организатор и участник) и они увидят друг друга.
"""
from __future__ import annotations

import os
import pickle
import time
from typing import Dict, Tuple

from ..errors import ОшибкаПлатформы
from .event import Мероприятие
from .session import УчастникСессии
from .user import Организатор, Пользователь


class Репозиторий:
    def __init__(self, путьКФайлу: str) -> None:
        self._путь: str = путьКФайлу
        self.пользователи: Dict[str, Пользователь] = {}
        self.мероприятия: Dict[str, Мероприятие] = {}
        self._времяФайла: float = 0.0   # когда файл менялся в последний раз
        os.makedirs(self.папкаДанных, exist_ok=True)
        self.загрузить()

    @property
    def папкаДанных(self) -> str:
        return os.path.dirname(os.path.abspath(self._путь))

    # ---------- работа с файлом ----------
    def загрузить(self) -> None:
        if not os.path.exists(self._путь):
            return
        try:
            with open(self._путь, "rb") as f:
                данные = pickle.load(f)
            self.пользователи = данные["пользователи"]
            self.мероприятия = данные["мероприятия"]
            self._времяФайла = os.path.getmtime(self._путь)
        except Exception as ошибка:  # файл битый — начинаем с пустого хранилища
            print("Не удалось прочитать хранилище, начинаю с чистого:", ошибка)

    def синхронизировать(self) -> None:
        """Если файл изменил другой процесс, перечитываем его."""
        if os.path.exists(self._путь) and os.path.getmtime(self._путь) != self._времяФайла:
            self.загрузить()

    def сохранить(self) -> None:
        временный = self._путь + ".tmp"
        with open(временный, "wb") as f:
            pickle.dump({"пользователи": self.пользователи,
                         "мероприятия": self.мероприятия}, f)
        # заменяем файл целиком, чтобы другой процесс не прочитал половину.
        # На Windows замена может не получиться, если файл прямо сейчас читают, — пробуем ещё раз.
        for попытка in range(5):
            try:
                os.replace(временный, self._путь)
                break
            except PermissionError:
                if попытка == 4:
                    raise
                time.sleep(0.05)
        self._времяФайла = os.path.getmtime(self._путь)

    # ---------- поиск ----------
    def найтиПользователя(self, ид: str) -> Пользователь:
        if ид not in self.пользователи:
            raise ОшибкаПлатформы("Пользователь не найден")
        return self.пользователи[ид]

    def найтиМероприятие(self, ид: str) -> Мероприятие:
        if ид not in self.мероприятия:
            raise ОшибкаПлатформы("Мероприятие не найдено")
        return self.мероприятия[ид]

    def этоОрганизатор(self, идМероприятия: str, идПользователя: str) -> bool:
        """Организатор ли этот пользователь именно этого мероприятия."""
        пользователь = self.пользователи.get(идПользователя)
        if not isinstance(пользователь, Организатор):
            return False
        мероприятие = self.мероприятия.get(идМероприятия)
        return мероприятие is not None and мероприятие in пользователь.мероприятия

    def найтиУчастника(self, идЗаписи: str) -> Tuple[Мероприятие, УчастникСессии]:
        for мероприятие in self.мероприятия.values():
            if мероприятие.сессия is None:
                continue
            for участник in мероприятие.сессия.участники:
                if участник.идЗаписи == идЗаписи:
                    return мероприятие, участник
        raise ОшибкаПлатформы("Участник сессии не найден")
