"""Мероприятие — центральный класс модели."""
from __future__ import annotations

import uuid
from typing import List, Optional

from ..constants import СТАТУС_СОЗДАНО
from .files import Файл
from .invitation import Приглашение
from .recording import ЗаписьВстречи
from .session import СессияСвязи
from .statistics import Статистика


class Мероприятие:
    def __init__(self, идМероприятия: str, тема: str, датаВремя: int, типДоступа: str,
                 запись: bool = True, залОжидания: bool = True) -> None:
        self.идМероприятия: str = идМероприятия
        self.тема: str = тема
        self.датаВремя: int = датаВремя      # Long: unix-время в секундах
        self.типДоступа: str = типДоступа
        self._статус: str = СТАТУС_СОЗДАНО   # на диаграмме -статус

        # [отклонение Д4] на макете создания мероприятия есть галочки «Включить запись»
        # и «Зал ожидания», а в классе под них атрибутов нет. Добавил два булевых поля.
        self.запись: bool = запись
        self.залОжидания: bool = залОжидания

        # Ниже связи из диаграммы классов (на диаграмме они нарисованы линиями,
        # а не атрибутами, поэтому в классе их не перечисляли, а в коде они нужны).
        self.приглашения: List[Приглашение] = []        # композиция, 0..*
        self.сессия: Optional[СессияСвязи] = None       # композиция, 0..1
        self.статистика: Статистика = Статистика(uuid.uuid4().hex[:8])  # агрегация, 1
        self.файлы: List[Файл] = []                     # агрегация, 0..*
        self.записи: List[ЗаписьВстречи] = []           # агрегация, 0..*
