"""Сессия связи и всё, что внутри неё: участники и сообщения чата."""
from __future__ import annotations

import time
from typing import List


class УчастникСессии:
    """Запись о том, что пользователь находится в сессии."""

    def __init__(self, идЗаписи: str, праваМикрофона: bool, статусПодключения: str,
                 идПользователя: str, имя: str) -> None:
        self.идЗаписи: str = идЗаписи
        self.праваМикрофона: bool = праваМикрофона
        self.статусПодключения: str = статусПодключения
        # [отклонение Д5] этих двух полей нет на диаграмме, но без них непонятно,
        # какой пользователь скрывается за записью и как подписать плитку в сетке
        self.идПользователя: str = идПользователя
        self.имя: str = имя


class СообщениеЧата:
    def __init__(self, идСообщения: str, текст: str, времяОтправки: int,
                 автор: str) -> None:
        self.идСообщения: str = идСообщения
        self.текст: str = текст
        self.времяОтправки: int = времяОтправки
        # [отклонение Д5] на диаграмме у сообщения нет автора, а в чате он нужен
        self.автор: str = автор


class СессияСвязи:
    """Онлайн-комната мероприятия."""

    def __init__(self, идСессии: str) -> None:
        self.идСессии: str = идСессии
        self.видеопоток: bool = True
        self.аудиопоток: bool = True
        self.демонстрацияЭкрана: bool = False
        # [отклонение Д5] время старта нужно, чтобы посчитать длительность записи
        self._началоСессии: int = int(time.time())
        # композиция: СессияСвязи 1 *-> 0..* УчастникСессии / СообщениеЧата
        self.участники: List[УчастникСессии] = []
        self.сообщения: List[СообщениеЧата] = []
