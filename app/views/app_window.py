"""ОкноПриложения — главное окно и «конечный автомат» переходов между экранами.

[отклонение Д3, Д10] В диаграмме классов такого класса нет. Нужен он потому, что
вход и регистрация происходят до того, как известна роль (и, значит, до создания
ИнтерфейсаОрганизатора/ИнтерфейсаУчастника), а КонтроллерПользователей в диаграмме
ни к одному классу интерфейса не привязан. Окно создаёт нужный интерфейс после входа.
"""
from __future__ import annotations

import json
import tkinter as tk
from tkinter import messagebox, ttk
from typing import Dict, Optional

from ..constants import РОЛЬ_ОРГАНИЗАТОР
from ..controllers import (КонтроллерМероприятий, КонтроллерПользователей,
                           КонтроллерСессии, КонтроллерХранения)
from ..errors import ОшибкаПлатформы
from .organizer_ui import ИнтерфейсОрганизатора
from .participant_ui import ИнтерфейсУчастника
from .screens import ЭкранВхода, ЭкранРегистрации
from .states import ПЕРЕХОДЫ, СостояниеUI


class ОкноПриложения:
    def __init__(self, контроллерПользователей: КонтроллерПользователей,
                 контроллерМероприятий: КонтроллерМероприятий,
                 контроллерСессии: КонтроллерСессии,
                 контроллерХранения: КонтроллерХранения) -> None:
        self._пользователи = контроллерПользователей
        self._мероприятия = контроллерМероприятий
        self._сессии = контроллерСессии
        self._хранение = контроллерХранения

        self._корень = tk.Tk()
        self._корень.title("Платформа для онлайн-конференций и вебинаров")
        self._корень.geometry("900x620")
        self._корень.minsize(760, 560)
        self._контейнер = ttk.Frame(self._корень)
        self._контейнер.pack(fill="both", expand=True)
        self._корень.protocol("WM_DELETE_WINDOW", self._закрытьОкно)

        self._состояние: Optional[СостояниеUI] = None   # None = начальное состояние
        self._текущийЭкран = None
        self._интерфейс = None   # ИнтерфейсОрганизатора или ИнтерфейсУчастника

    # ---------- доступ для экранов и интерфейсов ----------
    @property
    def корень(self) -> tk.Tk:
        return self._корень

    @property
    def контейнер(self) -> ttk.Frame:
        return self._контейнер

    @property
    def состояние(self) -> Optional[СостояниеUI]:
        return self._состояние

    @property
    def текущийЭкран(self):
        return self._текущийЭкран

    def показатьЭкран(self, экран) -> None:
        if self._текущийЭкран is not None:
            self._текущийЭкран.destroy()
        self._текущийЭкран = экран
        экран.pack(fill="both", expand=True)

    def скопироватьВБуфер(self, текст: str) -> None:
        self._корень.clipboard_clear()
        self._корень.clipboard_append(текст)

    # ---------- запуск и переходы ----------
    def запустить(self) -> None:
        self.перейти(СостояниеUI.ВХОД)   # переход «Запуск приложения»
        self._корень.mainloop()

    def перейти(self, новое: СостояниеUI, данные: Optional[Dict] = None) -> None:
        """Переход по диаграмме состояний интерфейса. Запрещённый переход — это ошибка в коде."""
        допустимые = {СостояниеUI.ВХОД} if self._состояние is None else ПЕРЕХОДЫ.get(self._состояние, set())
        if новое not in допустимые:
            raise ValueError("Нет перехода %s -> %s в диаграмме состояний" % (self._состояние, новое))
        self._состояние = новое
        if новое == СостояниеUI.ВХОД:
            self.показатьЭкран(ЭкранВхода(self._контейнер, self._войти,
                                         lambda: self.перейти(СостояниеUI.РЕГИСТРАЦИЯ)))
        elif новое == СостояниеUI.РЕГИСТРАЦИЯ:
            self.показатьЭкран(ЭкранРегистрации(self._контейнер, self._зарегистрироваться,
                                               lambda: self.перейти(СостояниеUI.ВХОД)))
        elif новое == СостояниеUI.ВЫХОД:
            self._завершить()
        else:
            описание = {"экран": новое}
            описание.update(данные or {})
            self._интерфейс.отобразить(описание)

    def выйти(self) -> None:
        """Кнопка «Выйти из системы» — переход в конечное состояние."""
        self.перейти(СостояниеUI.ВЫХОД)

    # ---------- вход и регистрация ----------
    def _войти(self, логин: str, пароль: str) -> None:
        ответ = self._пользователи.аутентификация(логин, пароль)
        if not ответ:
            messagebox.showerror("Вход", "Неверный логин или пароль")
            return
        сведения = json.loads(ответ)
        аргументы = (self, сведения["идПользователя"], self._мероприятия, self._сессии, self._хранение)
        # какой интерфейс показывать, зависит от роли
        if сведения["роль"] == РОЛЬ_ОРГАНИЗАТОР:
            self._интерфейс = ИнтерфейсОрганизатора(*аргументы)
        else:
            self._интерфейс = ИнтерфейсУчастника(*аргументы)
        self.перейти(СостояниеUI.ГЛАВНАЯ)

    def _зарегистрироваться(self, имя: str, email: str, пароль: str, повтор: str) -> None:
        if пароль != повтор:
            messagebox.showwarning("Регистрация", "Пароли не совпадают")
            return
        данные = json.dumps({"имя": имя, "email": email, "пароль": пароль}, ensure_ascii=False)
        try:
            self._пользователи.регистрация(данные)
        except ОшибкаПлатформы as ошибка:
            messagebox.showwarning("Регистрация", str(ошибка))
            return
        messagebox.showinfo("Регистрация", "Вы зарегистрированы. Теперь войдите в систему.")
        self.перейти(СостояниеUI.ВХОД)

    # ---------- закрытие ----------
    def _закрытьОкно(self) -> None:
        """Крестик окна: закрываем приложение из любого состояния."""
        self._завершить()

    def _завершить(self) -> None:
        if self._интерфейс is not None:
            self._интерфейс.завершитьРаботу()
        self._корень.destroy()
