"""ИнтерфейсОрганизатора — класс <<UI>> из пакета «Представление»."""
from __future__ import annotations

import datetime
import json
from tkinter import messagebox
from typing import Callable, Optional

from ..errors import ОшибкаПлатформы
from .base_ui import БазовыйИнтерфейс
from .screens import ОкноМодерации, ЭкранСозданияМероприятия
from .states import СостояниеUI


class ИнтерфейсОрганизатора(БазовыйИнтерфейс):
    def __init__(self, окно, идПользователя: str, контроллерМероприятий,
                 контроллерСессии, контроллерХранения) -> None:
        super().__init__(окно, контроллерМероприятий, контроллерСессии, контроллерХранения)
        self._идПользователя: str = идПользователя   # -идПользователя из диаграммы
        self._формаСоздания: Optional[ЭкранСозданияМероприятия] = None

    @property
    def _идТекущего(self) -> str:
        return self._идПользователя

    # ---------- методы из диаграммы ----------
    def создатьМероприятие(self) -> None:
        """Обработка кнопки «Сохранить и пригласить»: читаем форму и зовём контроллер."""
        данные = self._формаСоздания.получитьДанные()
        try:
            момент = datetime.datetime.strptime(данные["дата"] + " " + данные["время"], "%d.%m.%Y %H:%M")
        except ValueError:
            messagebox.showwarning("Создание мероприятия",
                                   "Проверьте дату и время: формат дд.мм.гггг и чч:мм")
            return
        строка = json.dumps({
            "идОрганизатора": self._идПользователя, "тема": данные["тема"],
            "датаВремя": int(момент.timestamp()), "типДоступа": "По ссылке",
            "запись": данные["запись"], "залОжидания": данные["залОжидания"],
        }, ensure_ascii=False)
        try:
            мероприятие = self._мероприятия.создатьМероприятие(строка)
        except ОшибкаПлатформы as ошибка:
            messagebox.showwarning("Создание мероприятия", str(ошибка))
            return
        ссылка = self._мероприятия.получитьСсылкуДоступа(мероприятие.идМероприятия)
        self._окно.скопироватьВБуфер(ссылка)
        messagebox.showinfo("Мероприятие создано",
                            "Приглашение создано. Ссылка скопирована в буфер обмена:\n" + ссылка)
        self._окно.перейти(СостояниеUI.ГЛАВНАЯ)

    def модерироватьВстречу(self) -> None:
        """Кнопка «Участники»: окно, где организатор пускает людей и раздаёт микрофон."""
        if self._окноМодерации is None or not self._окноМодерации.winfo_exists():
            self._окноМодерации = ОкноМодерации(self._окно.корень, self._допустить,
                                                self._микрофонУчастника)
        self._окноМодерации.lift()
        self._обновитьКонференцию()

    def просмотретьСтатистику(self, идМероприятия: str) -> None:
        self._окно.перейти(СостояниеUI.СТАТИСТИКА, {"идМероприятия": идМероприятия})

    # ---------- обработчики, которых нет в диаграмме ----------
    def _открытьФорму(self) -> None:
        self._окно.перейти(СостояниеUI.СОЗДАНИЕ)

    def _показатьСоздание(self) -> None:
        self._формаСоздания = ЭкранСозданияМероприятия(
            self._окно.контейнер, self.создатьМероприятие,
            lambda: messagebox.showinfo("Доступ", "Ссылка на мероприятие появится после сохранения."),
            lambda: self._окно.перейти(СостояниеUI.ГЛАВНАЯ))
        self._окно.показатьЭкран(self._формаСоздания)

    def _завершить(self) -> None:
        if not messagebox.askyesno("Завершить встречу", "Завершить встречу для всех участников?"):
            return
        self._завершаюСам = True
        try:
            self._мероприятия.завершитьВстречу(self._идМероприятия, self._идПользователя)
        except ОшибкаПлатформы as ошибка:
            self._завершаюСам = False
            messagebox.showwarning("Завершение встречи", str(ошибка))
            return
        self._идЗаписи = ""
        self._закрытьМодерацию()
        self._окно.перейти(СостояниеUI.СТАТИСТИКА, {"идМероприятия": self._идМероприятия})

    def _допустить(self, идЗаписи: str) -> None:
        try:
            self._сессии.допуститьУчастника(идЗаписи, self._идПользователя)
        except ОшибкаПлатформы as ошибка:
            messagebox.showwarning("Модерация", str(ошибка))
        self._обновитьКонференцию()

    def _микрофонУчастника(self, идЗаписи: str, вкл: bool) -> None:
        try:
            self._сессии.управлятьМикрофоном(идЗаписи, вкл, self._идПользователя)
        except ОшибкаПлатформы as ошибка:
            messagebox.showwarning("Модерация", str(ошибка))
        self._обновитьКонференцию()

    # ---------- какие кнопки показывать этой роли ----------
    def _колбэкСоздания(self) -> Optional[Callable]:
        return self._открытьФорму

    def _колбэкСтатистики(self) -> Optional[Callable]:
        return self.просмотретьСтатистику

    def _колбэкМодерации(self) -> Optional[Callable]:
        return self.модерироватьВстречу

    def _колбэкЗавершения(self) -> Optional[Callable]:
        return self._завершить
