"""Общая часть интерфейсов организатора и участника.

[отклонение Д9] В диаграмме ИнтерфейсОрганизатора и ИнтерфейсУчастника независимо
реализуют IПредставление. Но у них много общего (список мероприятий, экран конференции,
чат), и копировать этот код дважды не хотелось, поэтому вынес его в базовый класс.
Все методы из диаграммы остались в самих классах-наследниках.
"""
from __future__ import annotations

import csv
import datetime
from tkinter import filedialog, messagebox
from typing import Callable, Dict, List, Optional

from ..constants import (РОЛЬ_ОРГАНИЗАТОР, РОЛЬ_УЧАСТНИК, СТАТУС_ЗАВЕРШЕНО,
                         СТАТУС_СОЗДАНО, УЧ_ОЖИДАНИЕ)
from ..controllers import КонтроллерМероприятий, КонтроллерСессии, КонтроллерХранения
from ..errors import ОшибкаПлатформы
from .interfaces import IПредставление
from .screens import (ГлавнаяСтраница, ОкноМодерации, ЭкранКонференции,
                      ЭкранСтатистики, форматДаты)
from .states import СостояниеUI


class БазовыйИнтерфейс(IПредставление):
    def __init__(self, окно, контроллерМероприятий: КонтроллерМероприятий,
                 контроллерСессии: КонтроллерСессии,
                 контроллерХранения: КонтроллерХранения) -> None:
        self._окно = окно  # ОкноПриложения
        # [отклонение Д9] по диаграмме интерфейсу нужен один контроллер, но ему
        # приходится говорить с тремя (список мероприятий, чат, статистика, записи)
        self._мероприятия = контроллерМероприятий
        self._сессии = контроллерСессии
        self._хранение = контроллерХранения
        self._идМероприятия: str = ""     # мероприятие, в чьей комнате мы сейчас
        self._идЗаписи: str = ""          # наш идЗаписи как УчастникаСессии
        self._завершаюСам: bool = False   # организатор сам нажал «Завершить»
        self._окноМодерации: Optional[ОкноМодерации] = None

    @property
    def _идТекущего(self) -> str:
        """Идентификатор пользователя; в наследниках он хранится в поле из диаграммы."""
        raise NotImplementedError

    # ---------- IПредставление ----------
    def отобразить(self, данные: Dict) -> None:
        экран = данные["экран"]
        if экран == СостояниеUI.ГЛАВНАЯ:
            self._показатьГлавную()
        elif экран == СостояниеUI.СОЗДАНИЕ:
            self._показатьСоздание()
        elif экран == СостояниеUI.КОНФЕРЕНЦИЯ:
            self._показатьКонференцию(данные["идМероприятия"])
        elif экран == СостояниеUI.СТАТИСТИКА:
            self._показатьСтатистику(данные["идМероприятия"])

    def обновить(self, данные: Optional[Dict] = None) -> None:
        if self._окно.состояние == СостояниеUI.КОНФЕРЕНЦИЯ:
            self._обновитьКонференцию()
        elif self._окно.состояние == СостояниеUI.ГЛАВНАЯ:
            self._показатьГлавную()

    # ---------- переопределяются в наследниках ----------
    def _показатьСоздание(self) -> None:
        raise ОшибкаПлатформы("Эта роль не может создавать мероприятия")

    def _колбэкСоздания(self) -> Optional[Callable]:
        return None

    def _колбэкСтатистики(self) -> Optional[Callable]:
        return None

    def _колбэкМодерации(self) -> Optional[Callable]:
        return None

    def _колбэкЗавершения(self) -> Optional[Callable]:
        return None

    def _обработчикПодключения(self) -> Callable:
        return self._подключиться

    def _обработчикЧата(self) -> Callable:
        return self._отправитьСообщение

    def _обработчикЗаписи(self) -> Callable:
        return self._показатьЗапись

    # ---------- главная страница ----------
    def _показатьГлавную(self) -> None:
        self._закрытьМодерацию()
        карточки: List[dict] = []
        for м in self._мероприятия.получитьМероприятия(self._идТекущего):
            ид = м.идМероприятия
            этоОрг = self._мероприятия.являетсяОрганизатором(ид, self._идТекущего)
            карточки.append({
                "ид": ид, "тема": м.тема, "датаВремя": м.датаВремя,
                "роль": РОЛЬ_ОРГАНИЗАТОР if этоОрг else РОЛЬ_УЧАСТНИК,
                "статус": self._мероприятия.получитьСтатус(ид),
                "естьЗапись": self._хранение.получитьЗапись(ид) is not None,
            })
        экран = ГлавнаяСтраница(self._окно.контейнер, карточки, self._колбэкСоздания(),
                                self._обработчикПодключения(), self._колбэкСтатистики(),
                                self._обработчикЗаписи(), self._окно.выйти)
        self._окно.показатьЭкран(экран)

    # ---------- подключение к конференции ----------
    def _подключиться(self, идМероприятия: str) -> None:
        try:
            статус = self._мероприятия.получитьСтатус(идМероприятия)
            if статус == СТАТУС_ЗАВЕРШЕНО:
                messagebox.showinfo("Встреча завершена",
                                    "Эта встреча уже закончилась. Запись можно посмотреть кнопкой «Запись».")
                return
            # организатор своего мероприятия сначала открывает конференцию
            if статус == СТАТУС_СОЗДАНО and self._мероприятия.являетсяОрганизатором(идМероприятия, self._идТекущего):
                self._мероприятия.открытьКонференцию(идМероприятия, self._идТекущего)
            участник = self._сессии.подключитьУчастника(идМероприятия, self._идТекущего)
        except ОшибкаПлатформы as ошибка:
            messagebox.showwarning("Не удалось подключиться", str(ошибка))
            return
        self._идМероприятия = идМероприятия
        self._идЗаписи = участник.идЗаписи
        self._завершаюСам = False
        self._окно.перейти(СостояниеUI.КОНФЕРЕНЦИЯ, {"идМероприятия": идМероприятия})

    # ---------- экран конференции ----------
    def _показатьКонференцию(self, идМероприятия: str) -> None:
        этоОрг = self._мероприятия.являетсяОрганизатором(идМероприятия, self._идТекущего)
        колбэки = {
            "микрофон": self._переключитьМикрофон, "экран": self._переключитьДемонстрацию,
            "участники": self._колбэкМодерации(), "завершить": self._колбэкЗавершения(),
            "покинуть": self._покинуть, "выйти": self._окно.выйти,
            "сообщение": self._обработчикЧата(), "опрос": self.обновить,
        }
        тема = self._мероприятия.получитьМероприятие(идМероприятия).тема
        self._окно.показатьЭкран(ЭкранКонференции(self._окно.контейнер, тема, этоОрг, колбэки))
        self._обновитьКонференцию()

    def _обновитьКонференцию(self) -> None:
        ид = self._идМероприятия
        try:
            if self._мероприятия.получитьСтатус(ид) == СТАТУС_ЗАВЕРШЕНО and not self._завершаюСам:
                # организатор закончил встречу, пока мы сидели в комнате
                messagebox.showinfo("Встреча завершена", "Организатор завершил встречу.")
                self._идЗаписи = ""
                self._закрытьМодерацию()
                self._окно.перейти(СостояниеUI.ГЛАВНАЯ)
                return
            участники = [{"идЗаписи": у.идЗаписи, "имя": у.имя, "статус": у.статусПодключения,
                          "микрофон": у.праваМикрофона,
                          "организатор": self._мероприятия.являетсяОрганизатором(ид, у.идПользователя)}
                         for у in self._сессии.получитьУчастников(ид)]
            сообщения = [{"ид": с.идСообщения, "время": с.времяОтправки, "автор": с.автор, "текст": с.текст}
                         for с in self._сессии.получитьСообщения(ид)]
            сессия = self._мероприятия.получитьМероприятие(ид).сессия
            демонстрация = bool(сессия and сессия.демонстрацияЭкрана)
        except ОшибкаПлатформы:
            return
        я = next((у for у in участники if у["идЗаписи"] == self._идЗаписи), None)
        экран = self._окно.текущийЭкран
        if isinstance(экран, ЭкранКонференции):
            экран.показатьСостояние(участники, сообщения, я, демонстрация)
        if self._окноМодерации is not None:
            if self._окноМодерации.winfo_exists():
                self._окноМодерации.обновить(участники)
            else:
                self._окноМодерации = None

    def _переключитьМикрофон(self, вкл: bool) -> None:
        try:
            self._сессии.управлятьМикрофоном(self._идЗаписи, вкл, self._идТекущего)
        except ОшибкаПлатформы as ошибка:
            messagebox.showwarning("Микрофон", str(ошибка))
        self._обновитьКонференцию()

    def _переключитьДемонстрацию(self, вкл: bool) -> None:
        try:
            self._сессии.управлятьДемонстрацией(self._идМероприятия, вкл, self._идТекущего)
        except ОшибкаПлатформы as ошибка:
            messagebox.showwarning("Демонстрация экрана", str(ошибка))
        self._обновитьКонференцию()

    def _отправитьСообщение(self, текст: str) -> None:
        try:
            self._сессии.отправитьСообщение(self._идМероприятия, self._идТекущего, текст)
        except ОшибкаПлатформы as ошибка:
            messagebox.showwarning("Чат", str(ошибка))
        self._обновитьКонференцию()

    def _покинуть(self) -> None:
        """Выйти из комнаты, но не завершать встречу (переход КОНФЕРЕНЦИЯ -> ГЛАВНАЯ)."""
        self._сессии.отключитьУчастника(self._идЗаписи)
        self._идЗаписи = ""
        self._закрытьМодерацию()
        self._окно.перейти(СостояниеUI.ГЛАВНАЯ)

    def _закрытьМодерацию(self) -> None:
        if self._окноМодерации is not None:
            try:
                self._окноМодерации.destroy()
            except Exception:
                pass
            self._окноМодерации = None

    def завершитьРаботу(self) -> None:
        """Вызывается при закрытии приложения: если сидели в комнате — выходим из неё."""
        if self._идЗаписи:
            self._сессии.отключитьУчастника(self._идЗаписи)
            self._идЗаписи = ""

    # ---------- статистика ----------
    def _показатьСтатистику(self, идМероприятия: str) -> None:
        мероприятие = self._мероприятия.получитьМероприятие(идМероприятия)
        статистика = self._хранение.получитьСтатистику(идМероприятия)
        посещаемость = self._хранение.получитьПосещаемость(идМероприятия)
        экран = ЭкранСтатистики(
            self._окно.контейнер, мероприятие.тема, посещаемость,
            статистика.количествоУчастников, статистика.активностьВЧате,
            lambda: self._скачатьОтчёт(идМероприятия, посещаемость),
            lambda: self._окно.перейти(СостояниеUI.ГЛАВНАЯ))
        self._окно.показатьЭкран(экран)

    def _скачатьОтчёт(self, идМероприятия: str, посещаемость: int) -> None:
        мероприятие = self._мероприятия.получитьМероприятие(идМероприятия)
        статистика = self._хранение.получитьСтатистику(идМероприятия)
        путь = filedialog.asksaveasfilename(
            defaultextension=".csv", filetypes=[("CSV-файл", "*.csv")],
            initialfile="отчёт_%s.csv" % идМероприятия)
        if not путь:
            return  # пользователь передумал, остаёмся на экране статистики
        with open(путь, "w", newline="", encoding="utf-8-sig") as файл:
            писатель = csv.writer(файл, delimiter=";")
            писатель.writerow(["Мероприятие", мероприятие.тема])
            писатель.writerow(["Дата", форматДаты(мероприятие.датаВремя)])
            писатель.writerow(["Посещаемость, %", посещаемость])
            писатель.writerow(["Всего участников", статистика.количествоУчастников])
            писатель.writerow(["Сообщений в чате", статистика.активностьВЧате])
        messagebox.showinfo("Отчёт", "Отчёт сохранён:\n" + путь)
        self._окно.перейти(СостояниеUI.ГЛАВНАЯ)   # в диаграмме «Скачать отчет / Назад» ведут на главную

    # ---------- запись встречи ----------
    def _показатьЗапись(self, идМероприятия: str) -> None:
        запись = self._хранение.получитьЗапись(идМероприятия)
        if запись is None:
            messagebox.showinfo("Запись", "У этого мероприятия нет записи.")
            return
        минуты, секунды = divmod(запись.длительность, 60)
        messagebox.showinfo(
            "Запись встречи",
            "Дата записи: %s\nДлительность: %d мин %d с\nФайл: %s\n\n"
            "(Настоящего видеоплеера в этой версии нет, файл-заглушка лежит в папке data.)" %
            (форматДаты(запись.датаСоздания), минуты, секунды,
             self._хранение.получитьСсылкуНаЗапись(идМероприятия)))
