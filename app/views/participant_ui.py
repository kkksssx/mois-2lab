"""ИнтерфейсУчастника — класс <<UI>> из пакета «Представление»."""
from __future__ import annotations

from typing import Callable

from .base_ui import БазовыйИнтерфейс


class ИнтерфейсУчастника(БазовыйИнтерфейс):
    def __init__(self, окно, идУчастника: str, контроллерМероприятий,
                 контроллерСессии, контроллерХранения) -> None:
        super().__init__(окно, контроллерМероприятий, контроллерСессии, контроллерХранения)
        self._идУчастника: str = идУчастника   # -идУчастника из диаграммы

    @property
    def _идТекущего(self) -> str:
        return self._идУчастника

    # ---------- методы из диаграммы ----------
    def подключитьсяККонференции(self, идМероприятия: str) -> None:
        """Кнопка «Подключиться» на карточке мероприятия."""
        self._подключиться(идМероприятия)

    def взаимодействоватьВЧате(self, текст: str) -> None:
        """Отправка сообщения в чат конференции."""
        self._отправитьСообщение(текст)

    def просмотретьЗапись(self, идМероприятия: str) -> None:
        """Кнопка «Запись» на карточке завершённого мероприятия."""
        self._показатьЗапись(идМероприятия)

    # ---------- привязка к экранам ----------
    def _обработчикПодключения(self) -> Callable:
        return self.подключитьсяККонференции

    def _обработчикЧата(self) -> Callable:
        return self.взаимодействоватьВЧате

    def _обработчикЗаписи(self) -> Callable:
        return self.просмотретьЗапись
