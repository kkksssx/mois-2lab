"""Инжектор — собирает объекты приложения и передаёт зависимости.

[отклонение Д2] В базовой диаграмме нет классов со стереотипами <<injector>> и <<main>>
(это замечание к модели, п. 7.7 и 7.8 чек-листа). Но запустить приложение без них нельзя:
кто-то должен создать репозиторий, контроллеры и окно. Это делает этот класс,
а точкой входа служит main.py.
"""
from __future__ import annotations

import json
import os
import time

from .constants import РОЛЬ_ОРГАНИЗАТОР
from .controllers import (КонтроллерМероприятий, КонтроллерПользователей,
                          КонтроллерСессии, КонтроллерХранения)
from .model import Репозиторий


class Инжектор:  # <<injector>>
    def __init__(self, папкаДанных: str) -> None:
        self._папкаДанных = папкаДанных

    def собрать(self):
        """Создаёт все объекты и возвращает готовое окно приложения."""
        # импорт tkinter откладываем сюда, чтобы тесты логики работали без графики
        from .views.app_window import ОкноПриложения

        репозиторий = Репозиторий(os.path.join(self._папкаДанных, "storage.pkl"))   # <<create>>
        хранение = КонтроллерХранения(репозиторий)
        сессии = КонтроллерСессии(репозиторий, хранение)
        мероприятия = КонтроллерМероприятий(репозиторий, сессии)
        пользователи = КонтроллерПользователей(репозиторий)
        self._заполнитьДемоДанными(репозиторий, пользователи, мероприятия)
        return ОкноПриложения(пользователи, мероприятия, сессии, хранение)

    @staticmethod
    def _заполнитьДемоДанными(репозиторий, пользователи, мероприятия) -> None:
        """При первом запуске создаём тестовые аккаунты и два мероприятия."""
        if репозиторий.пользователи:
            return
        for имя, email, пароль in [("Преподаватель", "teacher@example.com", "teacher123"),
                                   ("Студент", "student@example.com", "student123"),
                                   ("Партнёр", "partner@example.com", "partner123")]:
            пользователи.регистрация(json.dumps({"имя": имя, "email": email, "пароль": пароль},
                                                ensure_ascii=False))
        ид = json.loads(пользователи.аутентификация("teacher@example.com", "teacher123"))["идПользователя"]
        пользователи.управлениеПравами(ид, РОЛЬ_ОРГАНИЗАТОР)
        сутки = 24 * 3600
        for тема, сдвиг, зал in [("Вебинар по Python", сутки, False),
                                 ("Созвон с командой", 2 * сутки, True)]:
            мероприятия.создатьМероприятие(json.dumps({
                "идОрганизатора": ид, "тема": тема, "датаВремя": int(time.time()) + сдвиг,
                "типДоступа": "По ссылке", "запись": True, "залОжидания": зал}, ensure_ascii=False))
